"""Generates src/sim/fixed_tables.inc: integer tables for the deterministic
fixed-point trigonometry (decision D-502).

The simulation never calls floating-point functions; it reads these
integers, so every machine and compiler gets the same results.

Usage: python tools/sim/make_trig_tables.py > src/sim/fixed_tables.inc
"""

import math

QUARTER = 1024        # Entries per quarter turn (plus one for the end point).
ONE = 1 << 16         # 16.16 fixed point.
TURN = 1 << 16        # Binary angle units per full turn.
CORDIC_STEPS = 16

print("// Generated by tools/sim/make_trig_tables.py. Do not edit.")
print("// sin(i / %d * 90 degrees) in 16.16 fixed point, i = 0..%d." % (QUARTER, QUARTER))
print("inline constexpr std::int32_t kSinQuarter[%d] = {" % (QUARTER + 1))
values = [round(math.sin(i / QUARTER * math.pi / 2) * ONE) for i in range(QUARTER + 1)]
for i in range(0, len(values), 12):
    print("    " + ", ".join(str(v) for v in values[i:i + 12]) + ",")
print("};")
print()
print("// atan(2^-i) in binary angle units (65536 per turn), for CORDIC.")
print("inline constexpr std::int32_t kCordicAngles[%d] = {" % CORDIC_STEPS)
angles = [round(math.atan(2.0 ** -i) / (2 * math.pi) * TURN) for i in range(CORDIC_STEPS)]
print("    " + ", ".join(str(a) for a in angles) + ",")
print("};")
